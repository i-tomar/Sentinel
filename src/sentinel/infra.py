"""Local infrastructure helpers: per-machine compose secrets and service health checks.

Compose secrets live in `.env.infra` (git-ignored, generated here), separate from the app's `.env`
because `Settings` rejects unknown keys. Health checks use only the standard library.
"""

from __future__ import annotations

