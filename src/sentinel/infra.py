import json
import secrets
import time
import urllib.error
import urllib.request
import uuid
from collections.abc import Callable, Mapping, Sequence
from pathlib import Path

from pydantic import BaseModel

INFRA_ENV_FILE = Path(".env.infra")
LANGFUSE_LOCAL_HOST = "http://localhost:3000"

_HEADER = """\
# Generated by `sentinel infra init` for local Docker Compose only. Do not commit.
# Changing these after the first `make up` breaks the existing volumes (stored passwords differ).
"""


def generate_infra_env() -> dict[str, str]:
    """Fresh random credentials for every service in docker-compose.yml."""
    return {
        "POSTGRES_PASSWORD": secrets.token_hex(16),
        "CLICKHOUSE_PASSWORD": secrets.token_hex(16),
        "REDIS_AUTH": secrets.token_hex(16),
        "MINIO_ROOT_PASSWORD": secrets.token_hex(16),
        "NEXTAUTH_SECRET": secrets.token_hex(32),
        "SALT": secrets.token_hex(32),
        "ENCRYPTION_KEY": secrets.token_hex(32),
        "LANGFUSE_INIT_ORG_ID": "sentinel-local",
        "LANGFUSE_INIT_ORG_NAME": "Sentinel (local)",
        "LANGFUSE_INIT_PROJECT_ID": "sentinel",
        "LANGFUSE_INIT_PROJECT_NAME": "sentinel",
        "LANGFUSE_INIT_PROJECT_PUBLIC_KEY": f"pk-lf-{uuid.uuid4()}",
        "LANGFUSE_INIT_PROJECT_SECRET_KEY": f"sk-lf-{uuid.uuid4()}",
        "LANGFUSE_INIT_USER_EMAIL": "dev@sentinel.test",
        "LANGFUSE_INIT_USER_NAME": "Sentinel Dev",
        "LANGFUSE_INIT_USER_PASSWORD": secrets.token_urlsafe(18),
    }


def render_env(values: Mapping[str, str]) -> str:
    return _HEADER + "".join(f"{key}={value}\n" for key, value in values.items())


def parse_env(text: str) -> dict[str, str]:
    values: dict[str, str] = {}
    for line in text.splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            key, _, value = line.partition("=")
            values[key.strip()] = value.strip()
    return values


def write_infra_env(path: Path = INFRA_ENV_FILE, *, force: bool = False) -> dict[str, str]:
    if path.exists() and not force:
        raise FileExistsError(path)
    values = generate_infra_env()
    path.write_text(render_env(values), encoding="utf-8", newline="\n")
    return values


def read_infra_env(path: Path = INFRA_ENV_FILE) -> dict[str, str]:
    return parse_env(path.read_text(encoding="utf-8"))


def app_env_lines(infra: Mapping[str, str], host: str = LANGFUSE_LOCAL_HOST) -> list[str]:
    """`.env` lines that point the app's tracing at the local Langfuse project."""
    return [
        "TRACING_BACKEND=langfuse",
        f"LANGFUSE_HOST={host}",
        f"LANGFUSE_PUBLIC_KEY={infra['LANGFUSE_INIT_PROJECT_PUBLIC_KEY']}",
        f"LANGFUSE_SECRET_KEY={infra['LANGFUSE_INIT_PROJECT_SECRET_KEY']}",
    ]


# --------------------------------------------------------------------------------------------
# Health checks
# --------------------------------------------------------------------------------------------


class CheckResult(BaseModel):
    name: str
    ok: bool
    detail: str


Fetch = Callable[[str, Mapping[str, str], float], tuple[int, bytes]]


def http_get(url: str, headers: Mapping[str, str], timeout: float) -> tuple[int, bytes]:
    if not url.startswith(("http://", "https://")):
        raise ValueError(f"refusing non-HTTP URL: {url}")
    request = urllib.request.Request(url, headers=dict(headers))  # noqa: S310 - scheme checked
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:  # noqa: S310
            return int(response.status), response.read()
    except urllib.error.HTTPError as exc:
        return exc.code, exc.read()


def _get(
    name: str, url: str, fetch: Fetch, timeout: float, headers: Mapping[str, str] | None = None
) -> tuple[int, bytes] | CheckResult:
    try:
        return fetch(url, headers or {}, timeout)
    except (OSError, ValueError) as exc:
        return CheckResult(name=name, ok=False, detail=f"unreachable: {exc}")


def _summary(status: int, body: bytes) -> str:
    return f"HTTP {status} {body.decode('utf-8', 'replace').strip()[:120]}".strip()


def check_qdrant(url: str, fetch: Fetch = http_get, timeout: float = 5.0) -> CheckResult:
    got = _get("qdrant", url.rstrip("/") + "/readyz", fetch, timeout)
    if isinstance(got, CheckResult):
        return got
    return CheckResult(name="qdrant", ok=got[0] == 200, detail=_summary(*got))


def check_langfuse_health(host: str, fetch: Fetch = http_get, timeout: float = 5.0) -> CheckResult:
    got = _get("langfuse", host.rstrip("/") + "/api/public/health", fetch, timeout)
    if isinstance(got, CheckResult):
        return got
    return CheckResult(name="langfuse", ok=got[0] == 200, detail=_summary(*got))


def check_langfuse_auth(
    host: str, public_key: str, secret_key: str, fetch: Fetch = http_get, timeout: float = 5.0
) -> CheckResult:
    """Verify the API keys authenticate. The secret key never appears in the result."""
    name = "langfuse-auth"
    token = base64.b64encode(f"{public_key}:{secret_key}".encode()).decode()
    url = host.rstrip("/") + "/api/public/projects"
    got = _get(name, url, fetch, timeout, {"Authorization": f"Basic {token}"})
    if isinstance(got, CheckResult):
        return got
    status, body = got
    if status != 200:
        return CheckResult(name=name, ok=False, detail=f"HTTP {status}: keys rejected")
    try:
        projects = json.loads(body).get("data", [])
    except (ValueError, AttributeError):
        return CheckResult(name=name, ok=False, detail="HTTP 200 but response is not JSON")
    names = ", ".join(str(p.get("name")) for p in projects if isinstance(p, dict)) or "?"
    return CheckResult(name=name, ok=True, detail=f"keys valid for project: {names}")


def wait_for(
    run: Callable[[], Sequence[CheckResult]],
    timeout_s: float,
    interval_s: float = 3.0,
    sleep: Callable[[float], None] = time.sleep,
    clock: Callable[[], float] = time.monotonic,
) -> list[CheckResult]:
    """Re-run checks until all pass or `timeout_s` elapses; returns the last results."""
    deadline = clock() + timeout_s
    while True:
        results = list(run())
        if all(r.ok for r in results) or clock() >= deadline:
            return results
        sleep(interval_s)
